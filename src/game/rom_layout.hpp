inline size_t romLayoutIndex(FireRedRevision revision){
    switch(revision){
    case FireRedRevision::FireRed_US_10:return 0;
    case FireRedRevision::FireRed_US_11:return 1;
    case FireRedRevision::LeafGreen_US_10:return 2;
    case FireRedRevision::LeafGreen_US_11:return 3;
    default:throw std::runtime_error("Unsupported game hook layout.");
    }
}
